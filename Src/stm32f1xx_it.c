void EXTI15_10_IRQHandler(void)
{
	HAL_GPIO_EXTI_IRQHandler(KEY_Pin);
}

void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
	if (htim == &htim3)
	{
		TimerCount++;
		if (TimerCount % 5 == 0)
		{
			/* 读取编码器速度 */
			Motor_Read_MotorSpeed(&speed1, &speed2);

			/* 更新里程（10ms一次，速度单位m/s，车轮直径7cm） */
			Mileage += 0.01f * (speed1 + speed2) / 2.0f * 0.2198f;

			TimerCount = 0;
		}
	}
}

/* 按键外部中断 — PC13 下降沿触发，用于任务切换 */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
	if (GPIO_Pin == KEY_Pin)
	{
		/* 软件去抖 */
		HAL_Delay(20);
		if (HAL_GPIO_ReadPin(KEY_GPIO_Port, KEY_Pin) == GPIO_PIN_RESET)
		{
			extern uint8_t g_TaskSelect;
			g_TaskSelect++;
			if (g_TaskSelect > 4) g_TaskSelect = 0;
		}
	}
}
